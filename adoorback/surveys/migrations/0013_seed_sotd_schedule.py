# Schedule the 20 SOTD (Survey of the Day) instruments on their assigned
# weekdays of the 4-week study (May 4 - May 31, 2026).
#
# Slug convention: `sotd_dNN_*` where NN = the study day number
# (1-indexed from May 4 kickoff). Weekend study days (6, 7, 13, 14, 20,
# 21, 27, 28) have no SOTD assigned — the slug numbering already skips
# them, and `_is_weekend_skipped` defends against accidentally serving
# any future SOTD that lands on a weekend.
#
# Sequence index 100+day_number to stay clear of:
#   - daily_base    (seq 1..28, from 0004)
#   - mock dailies  (seq 900..902)
#   - demo dailies  (seq 1000..1011)
#
# `get_today_daily` is updated in this same change set to prefer SOTD
# slugs over daily_base when both are scheduled on the same date — the
# diary continues to land in the index/archive but the SOTD takes the
# Survey-of-the-Day card.
from datetime import date, timedelta

from django.db import migrations


# Same kickoff anchor as 0004 + 0011 (post +1 day shift in 0012, the
# canonical kickoff is May 4). _day(n) is 1-indexed: day 1 = May 4.
STUDY_START = date(2026, 5, 4)


def _day(n: int) -> date:
    return STUDY_START + timedelta(days=n - 1)


# (study_day_number, slug) — sequence_index will be 100 + day_number.
# Generated by reading the slug: `sotd_dNN_*` → day = NN.
