def seed_sotd_schedule(apps, schema_editor):
    """Schedule each SOTD on its assigned study day.

    Idempotent — `update_or_create` keyed on (cadence, sequence_index).
    Short-circuits silently if Surveys are missing (matches 0004 / 0011).
    """
    Survey = apps.get_model('surveys', 'Survey')
    ScheduledSurvey = apps.get_model('surveys', 'ScheduledSurvey')
    if not Survey.objects.exists():
        return

    for day_n, slug in SOTD_SCHEDULE:
        try:
            survey = Survey.objects.get(slug=slug)
        except Survey.DoesNotExist:
            # Slug not loaded yet — setup_survey_state will retry next run.
            continue
        ScheduledSurvey.objects.update_or_create(
            cadence='daily',
            sequence_index=100 + day_n,
            defaults={
                'survey': survey,
                'window_start': _day(day_n),
                'window_end': _day(day_n),
                'allow_late': False,
            },
        )


def unseed_sotd_schedule(apps, schema_editor):
    ScheduledSurvey = apps.get_model('surveys', 'ScheduledSurvey')
    ScheduledSurvey.objects.filter(
        cadence='daily',
        sequence_index__in=[100 + n for n, _ in SOTD_SCHEDULE],
    ).delete()


